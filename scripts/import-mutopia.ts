/**
 * Fetches the chosen pieces from the Mutopia Project (their MIDI files), turns
 * them into Klavio's notes (MIDI → MusicXML → song/piece) and writes
 * shared/src/curriculum/classics.data.ts. Run again to refresh:
 *
 *   npx tsx scripts/import-mutopia.ts
 *
 * The compositions are in the public domain; the typesetting is licensed by
 * Mutopia under CC BY-SA – so every piece carries its credit and licence, and
 * the data file stays under that licence (see the file's header).
 */
import { writeFileSync } from 'node:fs';
import { importMusicXml, midiToMusicXml } from '../shared/src/index.ts';

interface Source {
  id: string;
  path: string;
  title: { 'de-CH': string; en: string };
  composer: string;
  pickupEighths?: number;
  /** Mutopia's reference, typesetter and licence (from the .ly header) */
  ref: string;
  typesetter: string;
  license: string;
  licenseUrl: string;
}

const SOURCES: Source[] = [
  {
    id: 'schumann-melodie',
    path: 'SchumannR/O68/schumann-op68-01-melodie',
    title: {
      'de-CH': 'Melodie (Album für die Jugend Nr. 1)',
      en: 'Melody (Album for the Young No. 1)',
    },
    composer: 'Robert Schumann',
    ref: 'Mutopia-2007/02/11-647',
    typesetter: 'Philippe Hézaine',
    license: 'CC BY-SA 2.5',
    licenseUrl: 'https://creativecommons.org/licenses/by-sa/2.5/',
  },
  {
    id: 'schumann-traellerliedchen',
    path: 'SchumannR/O68/schumann-op68-03-chanson-fredonnee',
    title: {
      'de-CH': 'Trällerliedchen (Album für die Jugend Nr. 3)',
      en: 'Humming Song (Album for the Young No. 3)',
    },
    composer: 'Robert Schumann',
    ref: 'Mutopia-2011/09/18-651',
    typesetter: 'Philippe Hézaine',
    license: 'CC BY-SA 3.0',
    licenseUrl: 'https://creativecommons.org/licenses/by-sa/3.0/',
  },
  {
    id: 'schumann-choral',
    path: 'SchumannR/O68/schumann-op68-04-choral',
    title: {
      'de-CH': 'Choral (Album für die Jugend Nr. 4)',
      en: 'Chorale (Album for the Young No. 4)',
    },
    composer: 'Robert Schumann',
    ref: 'Mutopia-2007/02/11-782',
    typesetter: 'Philippe Hézaine',
    license: 'CC BY-SA 2.5',
    licenseUrl: 'https://creativecommons.org/licenses/by-sa/2.5/',
  },
  {
    id: 'schumann-stueckchen',
    path: 'SchumannR/O68/schumann-op68-05-petite-piece',
    title: {
      'de-CH': 'Stückchen (Album für die Jugend Nr. 5)',
      en: 'Little Piece (Album for the Young No. 5)',
    },
    composer: 'Robert Schumann',
    // starts with an upbeat of three quarters (\partial 2.)
    pickupEighths: 6,
    ref: 'Mutopia-2007/02/11-653',
    typesetter: 'Philippe Hézaine',
    license: 'CC BY-SA 2.5',
    licenseUrl: 'https://creativecommons.org/licenses/by-sa/2.5/',
  },
];

const out: unknown[] = [];
for (const s of SOURCES) {
  const name = s.path.split('/').at(-1)!;
  const url = `https://www.mutopiaproject.org/ftp/${s.path}/${name}.mid`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const midi = new Uint8Array(await res.arrayBuffer());
  const piece = importMusicXml(
    midiToMusicXml(midi, {
      title: s.title['de-CH'],
      composer: s.composer,
      pickupEighths: s.pickupEighths,
    }),
  );
  out.push({
    id: s.id,
    title: s.title,
    composer: s.composer,
    keyboard: piece.keyboard,
    exercise: piece.exercise,
    source: {
      by: `Mutopia Project (${s.ref}), Notensatz ${s.typesetter}`,
      url: `https://www.mutopiaproject.org/cgibin/piece-info.cgi?id=${s.ref.split('-').at(-1)}`,
      license: s.license,
      licenseUrl: s.licenseUrl,
    },
  });
  console.log(`${s.id}: ${piece.kind}, ${piece.exercise.bars.length} bars`);
}

writeFileSync(
  new URL('../shared/src/curriculum/classics.data.ts', import.meta.url),
  `/*
 * Klavio's classical pieces to practise – generated by scripts/import-mutopia.ts,
 * do not edit by hand.
 *
 * The compositions are in the public domain. The notes were taken from the
 * Mutopia Project's editions (via their MIDI files) and simplified to Klavio's
 * note values; each piece names its source, typesetter and licence. This file
 * is licensed under the Creative Commons Attribution-ShareAlike licence of the
 * respective piece (CC BY-SA 2.5 / 3.0), not under the AGPL of the code.
 */
import type { ClassicPiece } from './classics.ts';

export const CLASSICS_DATA: ClassicPiece[] = ${JSON.stringify(out)};
`,
);
